<?php
/**
 * Roles & capabilities for StageKitWP Members.
 *
 * Defines three membership roles and a set of custom capabilities that the
 * rest of the plugin gates on (instead of generic list_users/manage_options):
 *
 *   - Member    : manage own profile, RSVP to events.
 *   - Producer  : Member + search members, email/message members, manage events.
 *   - Executive : Producer + manage members and plugin settings (full access).
 *
 * Roles are (re)registered on demand and version-gated so capability changes
 * roll out without a manual deactivate/reactivate. Administrators always get
 * every TM capability mirrored onto them.
 */

if (!defined('ABSPATH')) {
    exit;
}

class STAGEKITWP_MEMBERS_Roles {

    /**
     * Bump when the capability map below changes so roles re-sync on load.
     */
    const CAPS_VERSION = '1.0.3';

    const OPTION_KEY = 'stagekitwp_members_roles_version';

    /**
     * Custom capabilities this plugin checks against.
     */
    const CAP_MANAGE_PROFILE  = 'stagekitwp_members_manage_profile';
    const CAP_RSVP_EVENTS     = 'stagekitwp_members_rsvp_events';
    const CAP_SEARCH_MEMBERS  = 'stagekitwp_members_search_members';
    const CAP_MESSAGE_MEMBERS = 'stagekitwp_members_message_members';
    const CAP_SEND_EMAIL      = 'stagekitwp_members_send_email';
    const CAP_MANAGE_EVENTS   = 'stagekitwp_members_manage_events';
    const CAP_MANAGE_MEMBERS  = 'stagekitwp_members_manage_members';
    const CAP_MANAGE_SETTINGS = 'stagekitwp_members_manage_settings';

    public static function init() {
        // Called directly (not hooked) because this is itself invoked from
        // the plugin's own 'plugins_loaded' bootstrap at priority 20 — by
        // then 'plugins_loaded' has already passed priority 6, so a
        // newly-added priority-6 callback for that same hook would never
        // run on this request, and 'plugins_loaded' only fires once. Roles
        // and options are fully available at this point, so syncing here
        // directly is safe.
        self::maybe_sync();
    }

    /**
     * Full capability map per role. Each role inherits the ones below it.
     */
    public static function capabilities() {

        $member = [
            self::CAP_MANAGE_PROFILE,
            self::CAP_RSVP_EVENTS,
            // Members can browse the opt-in directory and message each other.
            self::CAP_SEARCH_MEMBERS,
            self::CAP_MESSAGE_MEMBERS,
        ];

        $producer = array_merge($member, [
            self::CAP_SEND_EMAIL,
            self::CAP_MANAGE_EVENTS,
        ]);

        $executive = array_merge($producer, [
            self::CAP_MANAGE_MEMBERS,
            self::CAP_MANAGE_SETTINGS,
        ]);

        return [
            'stagekitwp_member'    => ['name' => 'Member',    'caps' => $member],
            'stagekitwp_producer'  => ['name' => 'Producer',  'caps' => $producer],
            'stagekitwp_executive' => ['name' => 'Executive', 'caps' => $executive],
        ];
    }

    /**
     * Primitive caps generated by the stagekitwp_event CPT (capability_type =
     * ['stagekitwp_event','stagekitwp_events'], map_meta_cap = true). Granting these lets a
     * role create/edit/delete/publish events in wp-admin.
     */
    public static function event_caps() {
        return self::cpt_caps('stagekitwp_event', 'stagekitwp_events');
    }

    /**
     * Primitive caps generated by the stagekitwp_ann CPT (capability_type =
     * ['stagekitwp_ann','stagekitwp_anns'], map_meta_cap = true). Granting
     * these lets a role create/edit/delete/publish announcements in wp-admin.
     */
    public static function announcement_caps() {
        return self::cpt_caps('stagekitwp_ann', 'stagekitwp_anns');
    }

    /**
     * Primitive caps generated by the stagekitwp_email CPT (capability_type =
     * ['stagekitwp_email','stagekitwp_emails'], map_meta_cap = true). Granting
     * these lets a role create/edit/delete/publish email templates in wp-admin.
     */
    public static function email_template_caps() {
        return self::cpt_caps('stagekitwp_email', 'stagekitwp_emails');
    }

    /**
     * Build the full set of primitive capabilities WordPress derives for a
     * custom post type registered with the given singular/plural capability
     * names and map_meta_cap = true.
     */
    private static function cpt_caps($singular, $plural) {
        return [
            "edit_{$singular}",
            "read_{$singular}",
            "delete_{$singular}",
            "edit_{$plural}",
            "edit_others_{$plural}",
            "publish_{$plural}",
            "read_private_{$plural}",
            "delete_{$plural}",
            "delete_private_{$plural}",
            "delete_published_{$plural}",
            "delete_others_{$plural}",
            "edit_private_{$plural}",
            "edit_published_{$plural}",
        ];
    }

    /**
     * Every custom capability, flat. Used to grant admins full access.
     */
    public static function all_caps() {
        return [
            self::CAP_MANAGE_PROFILE,
            self::CAP_RSVP_EVENTS,
            self::CAP_SEARCH_MEMBERS,
            self::CAP_MESSAGE_MEMBERS,
            self::CAP_SEND_EMAIL,
            self::CAP_MANAGE_EVENTS,
            self::CAP_MANAGE_MEMBERS,
            self::CAP_MANAGE_SETTINGS,
        ];
    }

    /**
     * Re-sync roles only when the capability map version changes.
     */
    public static function maybe_sync() {
        if (get_option(self::OPTION_KEY) === self::CAPS_VERSION) {
            return;
        }
        self::register_roles();
        update_option(self::OPTION_KEY, self::CAPS_VERSION);
    }

    /**
     * Every primitive CPT capability granted by this plugin, flat. Used to
     * mirror onto administrators and to remove on deactivation.
     */
    public static function all_cpt_caps() {
        return array_merge(self::event_caps(), self::announcement_caps(), self::email_template_caps());
    }

    /**
     * Create/update all roles and mirror caps onto administrator. Idempotent.
     */
    public static function register_roles() {

        foreach (self::capabilities() as $slug => $role) {

            // add_role() is a no-op if the role exists, so remove first to
            // guarantee the capability set matches the current map exactly.
            remove_role($slug);

            $caps = ['read' => true];
            foreach ($role['caps'] as $cap) {
                $caps[$cap] = true;
            }

            // Roles that can manage events also get the Events and
            // Announcements CPT primitive caps (Producers post both).
            if (in_array(self::CAP_MANAGE_EVENTS, $role['caps'], true)) {
                foreach (array_merge(self::event_caps(), self::announcement_caps()) as $cap) {
                    $caps[$cap] = true;
                }
            }

            // Roles that can manage members also get the Email Templates
            // CPT primitive caps (Executives only).
            if (in_array(self::CAP_MANAGE_MEMBERS, $role['caps'], true)) {
                foreach (self::email_template_caps() as $cap) {
                    $caps[$cap] = true;
                }
            }

            add_role($slug, $role['name'], $caps);
        }

        // Administrators get every TM capability so wp-admin never locks out.
        $admin = get_role('administrator');
        if ($admin) {
            foreach (array_merge(self::all_caps(), self::all_cpt_caps()) as $cap) {
                $admin->add_cap($cap);
            }
        }
    }

    /**
     * Remove all roles and admin caps. Called on deactivation.
     */
    public static function remove_roles() {

        foreach (array_keys(self::capabilities()) as $slug) {
            remove_role($slug);
        }

        $admin = get_role('administrator');
        if ($admin) {
            foreach (array_merge(self::all_caps(), self::all_cpt_caps()) as $cap) {
                $admin->remove_cap($cap);
            }
        }

        delete_option(self::OPTION_KEY);
    }
}
